"""
Code generator: golden model  ->  RTL parity matrix + testbench vectors.

WHY GENERATE INSTEAD OF HAND-WRITING THE MATRIX
-----------------------------------------------
The project constraint is that the Python model is the source of truth. If the
RTL also built the H matrix from its own SystemVerilog implementation of the
Hsiao construction, a disagreement between the two would be a silent bug in
BOTH the design and its reference. Generating the table from the model removes
that failure mode entirely: there is exactly one implementation of the
construction, and the RTL is a transcription of its output.

This is also how real ECC IP is built -- DRAM controller RTL ships a hardcoded
H table emitted by a generator -- and it is the pattern Phase 3 needs anyway,
where the GF(2^m) log/antilog tables must be generated the same way.

Regenerate with:  python model/gen_rtl.py
check_up_to_date() in test_gen_rtl.py fails the build if the checked-in files
drift from the model.

Outputs:
  rtl/ecc_hsiao_pkg.sv      H matrix as a packed localparam + code geometry
  tb/vectors/secded_vectors.txt   directed vectors with expected outputs
  docs/h_matrix.md          human-readable H for the report
"""

import os
import random
import sys
from itertools import combinations

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hsiao import HsiaoCode, popcount

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_W, CHK_W = 64, 8


def gen_pkg(code: HsiaoCode) -> str:
    n, k, r = code.n, code.data_w, code.chk_w
    nib = (r + 3) // 4
    props = code.verify_properties()

    lines = [
        "// ---------------------------------------------------------------------------",
        "// ecc_hsiao_pkg.sv -- GENERATED FILE, DO NOT EDIT BY HAND",
        "//",
        "//   Generated by model/gen_rtl.py from the golden model in model/hsiao.py.",
        "//   Regenerate:  python model/gen_rtl.py",
        "//",
        f"//   Hsiao SEC-DED ({n},{k}) parity-check matrix, systematic: H = [ A | I_{r} ].",
        "//",
        "//   Bit numbering (used identically in the model, the RTL and the TB):",
        f"//     code[{k - 1}:0]   = data",
        f"//     code[{n - 1}:{k}]  = check bits",
        "//     H_COL[j] is the parity-check column for code bit j.",
        "//",
        "//   Properties verified by model/test_hsiao.py:",
        f"//     every column nonzero, odd weight, distinct   => d_min >= 4",
        f"//     a weight-4 codeword exists                   => d_min == 4 exactly",
        f"//     column weight histogram {props['col_weight_histogram']}"
        f" (minimum possible total weight)",
        f"//     row weights {props['row_weights']}"
        f" -- perfectly balanced, so every",
        f"//       parity tree has the same {props['row_weights'][0]}-input fan-in"
        " (shortest critical path)",
        f"//     total H weight {props['total_weight']}"
        f" = XOR gate inputs across all {r} parity trees",
        "// ---------------------------------------------------------------------------",
        "",
        "package ecc_hsiao_pkg;",
        "",
        f"  localparam int unsigned ECC_DATA_W = {k};",
        f"  localparam int unsigned ECC_CHK_W  = {r};",
        f"  localparam int unsigned ECC_CODE_W = {n};",
        "",
        "  typedef logic [ECC_CHK_W-1:0] ecc_syndrome_t;",
        "",
        "  // Packed array of the H columns. Emitted as a concatenation in",
        "  // DESCENDING index order, which is unambiguous in SystemVerilog",
        f"  // (leftmost element is the highest index, H_COL[{n - 1}]).",
        "  localparam logic [ECC_CODE_W-1:0][ECC_CHK_W-1:0] H_COL = {",
    ]

    for j in range(n - 1, -1, -1):
        col = code.h[j]
        bits = "".join("1" if (col >> i) & 1 else "0" for i in range(r - 1, -1, -1))
        kind = "check" if j >= k else "data "
        comma = "," if j > 0 else ""
        lines.append(
            f"    {r}'h{col:0{nib}X}{comma}"
            f"{'':<{2 if comma else 3}}// col {j:2d}  {kind} {bits}  wt={popcount(col)}"
        )

    lines += [
        "  };",
        "",
        "endpackage : ecc_hsiao_pkg",
        "",
    ]
    return "\n".join(lines)


def gen_vectors(code: HsiaoCode, seed: int = 20260101) -> str:
    """
    Directed vectors: one test per line, whitespace separated.

        data  code  err  exp_data  exp_syndrome  exp_det exp_cor exp_unc

    The TB also does its own exhaustive injection and self-checks against the
    data it encoded, so these vectors exist to pin the RTL to the golden
    model's EXACT H matrix and flag semantics -- if the RTL used a different
    (but still valid) Hsiao matrix, the codeword and syndrome columns here
    would mismatch immediately.
    """
    rng = random.Random(seed)
    n, k, r = code.n, code.data_w, code.chk_w
    dn, cn, sn = (k + 3) // 4, (n + 3) // 4, (r + 3) // 4

    tests = []  # (data, error_mask)

    # Corner data patterns with no error
    corners = [0, (1 << k) - 1, 0xAAAAAAAAAAAAAAAA, 0x5555555555555555,
               0x0123456789ABCDEF, 0xDEADBEEFCAFEBABE]
    for d in corners:
        tests.append((d, 0))

    # Every single-bit position, against two different data backdrops
    for d in (0x0123456789ABCDEF, 0xFFFFFFFFFFFFFFFF):
        for pos in range(n):
            tests.append((d, 1 << pos))

    # Every adjacent pair (the realistic multi-bit burst for a DRAM/link fault)
    d = 0xDEADBEEFCAFEBABE
    for pos in range(n - 1):
        tests.append((d, (1 << pos) | (1 << (pos + 1))))

    # Random errors of weight 0..5
    for _ in range(3000):
        d = rng.getrandbits(k)
        w = rng.choice([0, 1, 1, 1, 2, 2, 2, 3, 4, 5])
        e = 0
        for p in rng.sample(range(n), w):
            e |= 1 << p
        tests.append((d, e))

    out = [
        "// GENERATED by model/gen_rtl.py -- do not edit",
        "// data code err exp_data exp_syndrome exp_det exp_cor exp_unc",
    ]
    for d, e in tests:
        cw = code.encode(d)
        res = code.decode(cw ^ e)
        out.append(
            f"{d:0{dn}x} {cw:0{cn}x} {e:0{cn}x} "
            f"{res['data']:0{dn}x} {res['syndrome']:0{sn}x} "
            f"{int(res['detected'])} {int(res['corrected'])} "
            f"{int(res['uncorrectable'])}"
        )
    return "\n".join(out) + "\n"


def gen_h_doc(code: HsiaoCode) -> str:
    n, k, r = code.n, code.data_w, code.chk_w
    props = code.verify_properties()
    lines = [
        f"# Parity-check matrix H -- Hsiao SEC-DED ({n},{k})",
        "",
        "Generated by `model/gen_rtl.py`. Systematic form `H = [ A | I_8 ]`:",
        f"columns 0..{k - 1} are data bits, columns {k}..{n - 1} are check bits.",
        "",
        "A codeword satisfies `H . c = 0 (mod 2)`. The syndrome of a received",
        "word is `S = H . r = H . e`, which depends only on the error, so a",
        f"single flip at position p yields S = column p.",
        "",
        "## Properties",
        "",
        "| property | value | why it matters |",
        "|---|---|---|",
        f"| columns nonzero | {props['h1_all_nonzero']} | a flip is always visible |",
        f"| columns odd weight | {props['h2_all_odd_weight']} | syndrome parity = error count mod 2 (free DED) |",
        f"| columns distinct | {props['h3_all_distinct']} | a flip is unambiguously locatable |",
        f"| d_min | 4 | correct 1 **and** detect 2 simultaneously |",
        f"| column weights | {props['col_weight_histogram']} | minimum legal total weight = minimum XOR area |",
        f"| row weights | all {props['row_weights'][0]} | balanced -> shortest critical path |",
        f"| total weight | {props['total_weight']} | total XOR gate inputs |",
        "",
        "## Matrix",
        "",
        f"Row i below is parity equation i. Columns are code bits {n - 1} down to 0",
        "(left to right), matching Verilog bit order.",
        "",
        "```",
    ]
    header = "      " + "".join(
        str((j // 10) % 10) if j % 10 == 0 else " " for j in range(n - 1, -1, -1))
    ruler = "      " + "".join(str(j % 10) for j in range(n - 1, -1, -1))
    lines += [header, ruler]
    for i in range(r):
        row = "".join("1" if (code.h[j] >> i) & 1 else "." for j in range(n - 1, -1, -1))
        wt = sum(1 for j in range(n) if (code.h[j] >> i) & 1)
        lines.append(f"  r{i}  {row}  wt={wt}")
    lines += ["```", ""]
    lines += [
        "Legend: `1` = bit participates in that parity equation, `.` = it does not.",
        f"The rightmost {r} columns are the identity block: check bit i appears in",
        "exactly one equation, which is what makes the encoder a direct read-off.",
        "",
    ]
    return "\n".join(lines)


def main():
    code = HsiaoCode(DATA_W, CHK_W)
    props = code.verify_properties()
    if not props["d_min_ge_4"]:
        sys.exit("refusing to generate: matrix fails Hsiao's rules")

    targets = {
        os.path.join(REPO, "rtl", "ecc_hsiao_pkg.sv"): gen_pkg(code),
        os.path.join(REPO, "tb", "vectors", "secded_vectors.txt"): gen_vectors(code),
        os.path.join(REPO, "docs", "h_matrix.md"): gen_h_doc(code),
    }
    for path, text in targets.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", newline="\n") as f:
            f.write(text)
        nlines = text.count("\n")
        print(f"  wrote {os.path.relpath(path, REPO)}  ({nlines} lines)")
    print(f"\nHsiao SEC-DED ({code.n},{code.data_w}): "
          f"row weights {props['row_weights']}, total weight {props['total_weight']}")


if __name__ == "__main__":
    main()
